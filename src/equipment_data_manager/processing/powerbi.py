EXPORT_VERSION = 'powerbi-v1'
COMMON = ('RecordId', 'ReportMonth', 'SourceSystem', 'ReportType', 'SourceFileName', 'SourceFileSHA256',
          'SourceRecordNumber', 'CandidateRecordNumber', 'LegacyCandidateSHA256', 'CleanerVersion',
          'ExportVersion', 'SchemaVersion', 'ValidationStatus')
BUSINESS = {
    ReportType.REPAIRS: ('LegacyRowNumber', 'CompletedDate', 'EquipmentName', 'EquipmentId', 'Location',
        'ServiceVendor', 'RepairCount', 'RepairPersonHours', 'PartsCost', 'LaborCost', 'EstimatedTotalCost',
        'LegacyPartsCost', 'LegacyEstimatedTotalCost', 'RawPartsCost', 'RawTextbox16', 'Description', 'Details',
        'AccountName', 'RawEquipmentId'),
    ReportType.SERVICE_ORDERS: ('EquipmentId', 'EquipmentName', 'ScheduledDate', 'CompletedDate', 'Location',
        'Description', 'Status', 'RawStatus', 'EstimatedPrice', 'RawDescription', 'SourceMaintenanceTag', 'AccountName',
        'SourceVendorName', 'RawCost', 'RawEquipmentId'),
    ReportType.TMA_WORK_ORDERS: ('WorkOrderId', 'RequestDate', 'Requestor', 'Request', 'AssignedTo'),
}
DATES = {'CompletedDate', 'ScheduledDate', 'RequestDate'}
INTEGERS = {'LegacyRowNumber', 'RepairCount', 'SourceRecordNumber', 'CandidateRecordNumber'}
DECIMALS = {'RepairPersonHours', 'PartsCost', 'LaborCost', 'EstimatedTotalCost',
            'LegacyPartsCost', 'LegacyEstimatedTotalCost', 'EstimatedPrice'}


def schema(kind):
    return tuple(ColumnSchema(name, 'date' if name in DATES else 'integer' if name in INTEGERS
                              else 'decimal' if name in DECIMALS else 'text')
                 for name in BUSINESS[kind] + COMMON)


def number(value, *, integer=False, nullable=False):
    if value == '' and nullable:
        return ''
    try:
        parsed = Decimal(value)
        if not parsed.is_finite() or (integer and parsed != parsed.to_integral_value()):
            raise InvalidOperation
        return str(int(parsed)) if integer else format(parsed, 'f')
    except (InvalidOperation, ValueError):
        raise ProcessingError('invalid_normalized_number') from None


def iso_date(value, *, legacy_format='%Y-%m-%d', nullable=True):
    if value == '' and nullable:
        return ''
    try:
        parsed = datetime.strptime(value, legacy_format).date()
        if parsed.strftime(legacy_format) != value:
            raise ValueError
        return parsed.isoformat()
    except ValueError:
        raise ProcessingError('invalid_normalized_date') from None


def source_money_available(value):
    if not value.strip():
        return False
    try:
        return Decimal(value.strip().replace('$', '').replace(',', '')).is_finite()
    except InvalidOperation:
        return False


def candidate_rows(candidate, kind):
    """Read only the exact CSV representation generated by the existing adapter."""
    try:
        rows = list(csv.reader(StringIO(candidate.output_bytes.decode('utf-8'), newline=''), strict=True))
    except (UnicodeError, csv.Error):
        raise ProcessingError('invalid_legacy_export_schema') from None
    header_index, columns = {
        ReportType.REPAIRS: (3, repairs.OUTPUT_COLUMNS),
        ReportType.SERVICE_ORDERS: (0, service.SERVICE_COLUMNS),
        ReportType.TMA_WORK_ORDERS: (1, requests.REQUEST_COLUMNS),
    }[kind]
    if len(rows) <= header_index or rows[header_index] != columns:
        raise ProcessingError('invalid_legacy_export_schema')
    body = rows[header_index + 1:]
    if len(body) != candidate.output_rows or not body or any(len(row) != len(columns) for row in body):
        raise ProcessingError('invalid_legacy_export_schema')
    return [dict(zip(columns, row)) for row in body]


def business_row(kind, row, raw):
    if kind == ReportType.REPAIRS:
        known_parts = source_money_available(raw.get('Textbox38', ''))
        # Copy the existing calculated numbers; do not implement another formula.
        parts, total = number(row['Parts Cost $']), number(row['Est. Total $'])
        identifier = row['Equipment ID']
        return dict(LegacyRowNumber=number(row['#'], integer=True),
            CompletedDate=iso_date(row['Completed Date'], nullable=False), EquipmentName=row['Equipment Name'],
            EquipmentId=repairs.extract_label(raw.get('PersonnelId1', ''), 'Equipment Id') if identifier else '',
            Location=row['Location'], ServiceVendor=row['Service Vendor'],
            RepairCount=number(row['# of Repairs'], integer=True), RepairPersonHours=number(row['Repair Person-Hrs']),
            PartsCost=parts if known_parts else '', LaborCost=number(row['Total Labor $']),
            EstimatedTotalCost=total if known_parts else '', LegacyPartsCost=parts, LegacyEstimatedTotalCost=total,
            RawPartsCost=raw.get('Textbox38', ''), RawTextbox16=raw.get('Textbox16', ''),
            Description=raw.get('Description', ''), Details=raw.get('Details', ''),
            AccountName=raw.get('AccountName2', ''), RawEquipmentId=raw.get('PersonnelId1', ''))
    if kind == ReportType.SERVICE_ORDERS:
        description = raw.get('Description', '')
        tag = re.search(r'\((PM|Repair)\)\s*$', description, re.I)
        return dict(EquipmentId=raw.get('EquipmentId1', '').strip() if row['Equipment Id'] else '',
            EquipmentName=row['Equipment Name'], ScheduledDate=iso_date(row['Sched. Date']),
            CompletedDate=iso_date(row['Completed Date']), Location=row['Location'], Description=row['Description'],
            Status=row['Status'], RawStatus=raw.get('Textbox21', ''), EstimatedPrice=number(row['Estimated Price'], nullable=True),
            RawDescription=description, SourceMaintenanceTag=('PM' if tag.group(1).lower() == 'pm' else 'Repair') if tag else '',
            AccountName=raw.get('AccountName2', ''), SourceVendorName=raw.get('VendorName', ''),
            RawCost=raw.get('Cost', ''), RawEquipmentId=raw.get('EquipmentId1', ''))
    return dict(WorkOrderId=row['Work Order #'],
                RequestDate=iso_date(row['Request Date'], legacy_format='%m/%d/%Y', nullable=False),
                Requestor=row['Requestor'], Request=row['Request'], AssignedTo=row['Assigned To'])


class PowerBiCleaner:
    """Wrap a real legacy adapter. A normalized success is never publication approval."""

    def __init__(self, kind, base):
        self.kind, self.base = ReportType(kind), base
        self.version = f'{EXPORT_VERSION}:{base.version}'

    def clean(self, raw_bytes, *, source_name, period):
        candidate = self.base.clean(raw_bytes, source_name=source_name, period=period)
        if candidate.cleaner_version != self.base.version or candidate.source_period != period:
            raise ProcessingError('cleaner_contract_mismatch')
        rows = candidate_rows(candidate, self.kind)
        source_hash, legacy_hash = sha256(raw_bytes).hexdigest(), sha256(candidate.output_bytes).hexdigest()
        source_numbers, source_rows = [''] * len(rows), [{} for _ in rows]
        notes = [note.replace('unmapped_source_columns:', 'legacy_unmapped_source_columns:', 1)
                 if note.startswith('unmapped_source_columns:') else note for note in candidate.warnings]
        notes.append('production_publication_blocked')
        if self.kind != ReportType.TMA_WORK_ORDERS:
            diagnostics = candidate.diagnostics
            if diagnostics is None or diagnostics.source_sha256 != source_hash:
                raise ProcessingError('normalization_source_alignment_failed')
            original = list(csv.DictReader(StringIO(raw_bytes.decode('utf-8-sig'), newline='')))
            accepted = [entry.record for entry in diagnostics.records if entry.retained_by_cleaner]
            if (len(original) != candidate.input_rows or len(accepted) != len(rows)
                    or accepted != sorted(set(accepted)) or any(index < 1 or index > len(original) for index in accepted)):
                raise ProcessingError('normalization_source_alignment_failed')
            source_numbers = accepted
            source_rows = [original[index - 1] for index in accepted]
            known = SummaryRepairsLayout.HEADERS if self.kind == ReportType.REPAIRS else SummaryServiceOrdersLayout.HEADERS | {'Cost', 'Location'}
            unknown = len(set(original[0]) - known)
            if unknown:
                notes.append(f'normalized_unmapped_source_columns:{unknown}')
        elif candidate.input_rows == candidate.output_rows:
            source_numbers = list(range(1, len(rows) + 1))
        else:
            notes.append('source_record_numbers_unavailable')
        normalized = []
        null_financial = 0
        for ordinal, (row, raw, source_number) in enumerate(zip(rows, source_rows, source_numbers), 1):
            result = business_row(self.kind, row, raw)
            if self.kind == ReportType.REPAIRS and not source_money_available(raw.get('Textbox38', '')):
                null_financial += 1
            result.update(RecordId=sha256(f'{self.kind}:{period}:{source_hash}:{self.base.version}:{ordinal}'.encode()).hexdigest(),
                ReportMonth=period, SourceSystem='TMA' if self.kind == ReportType.TMA_WORK_ORDERS else 'CompuClean',
                ReportType=self.kind.value, SourceFileName=source_name.replace('\\', '/').rsplit('/', 1)[-1],
                SourceFileSHA256=source_hash, SourceRecordNumber=source_number, CandidateRecordNumber=ordinal,
                LegacyCandidateSHA256=legacy_hash, CleanerVersion=self.base.version, ExportVersion=EXPORT_VERSION,
                SchemaVersion='1', ValidationStatus='CandidateUnverified')
            normalized.append(result)
        if null_financial:
            notes.append(f'normalized_financial_values_unavailable:{null_financial}')
        contract = schema(self.kind)
        columns = [column.name for column in contract]
        if any(set(row) != set(columns) for row in normalized):
            raise ProcessingError('invalid_normalized_schema')
        output = StringIO(newline='')
        writer = csv.DictWriter(output, fieldnames=columns)
        writer.writeheader()
        writer.writerows(normalized)
        metrics = tuple(ReconciliationMetric(f'Legacy {m.name}', m.value, m.unit)
                        for m in candidate.reconciliation_metrics)
        metrics += (ReconciliationMetric('Normalized rows', Decimal(len(normalized)), 'count'),)
        return replace(candidate, output_bytes=output.getvalue().encode('utf-8'), schema=contract,
                       cleaner_version=self.version, warnings=tuple(notes), reconciliation_metrics=metrics)


def powerbi_coordinator(output_root):
    """Candidate-only storage; no approved-current folder or publisher exists."""
    from equipment_data_manager.processing.coordinator import ProcessingCoordinator
    bases = {kind: LegacyCsvCleaner(kind) for kind in (ReportType.REPAIRS, ReportType.SERVICE_ORDERS)}
    bases[ReportType.TMA_WORK_ORDERS] = TmaXlsxCleaner()
    return ProcessingCoordinator(Path(output_root) / 'powerbi_candidates',
                                 cleaners={kind: PowerBiCleaner(kind, base) for kind, base in bases.items()})
